        </li>
        <li>
            In the
            <strong>IP Address</strong>
            field, paste the server IP address shown bellow in our form.
        </li>
        <li>
            Click
            <strong>Add API Key</strong>
            to create the key.
        </li>
        <li>Once created, you'll see your new API key in the list with status "Enabled".</li>
        <li>
            <strong>Copy the API Key</strong>
            from the table and paste it into the
            <strong>API Key</strong>
            field below.
        </li>
        <li>
            Note your
            <strong>Reseller ID</strong>
            (shown as "Your Reseller ID is *****" in the blue notification bar) and enter it in the
            <strong>Reseller ID</strong>
            field below.
